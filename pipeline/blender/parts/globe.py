def _fill(poly, W, H):
    """Even-odd scanline fill of a lon/lat polygon on a W x H equirectangular grid (row 0 = 90 S)."""
    out = np.zeros((H, W), bool)
    x0, y0 = poly[:, 0], poly[:, 1]
    x1, y1 = np.roll(x0, -1), np.roll(y0, -1)
    lat = -90.0 + (np.arange(H) + 0.5) * 180.0 / H
    lo, hi = np.searchsorted(lat, y0.min()), np.searchsorted(lat, y0.max())
    for r in range(lo, min(hi + 1, H)):
        L = lat[r]
        c = (y0 <= L) != (y1 <= L)
        if not c.any():
            continue
        xs = np.sort(x0[c] + (L - y0[c]) * (x1[c] - x0[c]) / (y1[c] - y0[c]))
        cols = (xs + 180.0) / 360.0 * W
        for a, b in zip(cols[0::2], cols[1::2]):
            out[r, max(0, int(round(a))):min(W, int(round(b)))] = True
    return out


def _blur(a, rad):
    """Separable box blur (applied twice, about Gaussian), wrapping in longitude."""
    if rad < 1:
        return a
    k = 2 * rad + 1
    for _ in range(2):
        p = np.concatenate([a[:, -rad:], a, a[:, :rad]], axis=1)
        c = np.cumsum(np.pad(p, ((0, 0), (1, 0))), axis=1)
        a = (c[:, k:] - c[:, :-k]) / k
        p = np.pad(a, ((rad, rad), (0, 0)), mode="edge")
        c = np.cumsum(np.pad(p, ((1, 0), (0, 0))), axis=0)
        a = (c[k:, :] - c[:-k, :]) / k
    return a


def _gauss(W, H, rows, sigma_scale=1.0):
    """Sum of Gaussians on the sphere's grid: rows of (lat, lon, radius_deg, weight)."""
    lat = np.radians(-90.0 + (np.arange(H) + 0.5) * 180.0 / H)[:, None]
    lon = np.radians(-180.0 + (np.arange(W) + 0.5) * 360.0 / W)[None, :]
    cl, sl = np.cos(lat), np.sin(lat)
    acc = np.zeros((H, W))
    for la, lo, r, w in rows:
        la_, lo_ = math.radians(la), math.radians(lo)
        r_ = math.radians(r * sigma_scale)
        # only the rows near it
        r0 = max(0, int((math.degrees(la_ - 3.2 * r_) + 90) / 180 * H) - 1)
        r1 = min(H, int((math.degrees(la_ + 3.2 * r_) + 90) / 180 * H) + 2)
        cosd = sl[r0:r1] * math.sin(la_) + cl[r0:r1] * math.cos(la_) * np.cos(lon - lo_)
        d = np.arccos(np.clip(cosd, -1.0, 1.0))
        acc[r0:r1] += w * np.exp(-0.5 * (d / r_) ** 2)
    return acc


@lru_cache(maxsize=2)
def maps(W=2048, H=1024):
    """Equirectangular maps (row 0 = 90 S, column 0 = 180 W), values 0..1: land (softened coast), people (relative
    density, for city lights and the counter), desert, ice."""
    SS = 2
    land = np.zeros((H * SS, W * SS), bool)
    for s in (AFRO_EURASIA, NORTH_AMERICA, SOUTH_AMERICA, *ISLANDS.values()):
        land |= _fill(_pts(s), W * SS, H * SS)
    for s in LAKES.values():
        land &= ~_fill(_pts(s), W * SS, H * SS)
    land_f = land.reshape(H, SS, W, SS).mean(axis=(1, 3))
    land_s = np.clip(_blur(land_f, 1), 0.0, 1.0)

    ice = np.zeros((H * SS, W * SS), bool)
    for k in ICE:
        ice |= _fill(_pts(ISLANDS[k]), W * SS, H * SS)
    ice_f = ice.reshape(H, SS, W, SS).mean(axis=(1, 3))
    lat_deg = (-90.0 + (np.arange(H) + 0.5) * 180.0 / H)[:, None]
    # Greenland keeps a bare rocky rim; Arctic sea ice past ~80 N in the autumn
    ice_f = np.clip(_blur(ice_f, 2) * 1.25 - 0.18, 0.0, 1.0)
    sea_ice = np.clip((lat_deg - 79.0) / 3.0, 0.0, 1.0) * (1.0 - land_s)
    ice_f = np.maximum(ice_f, sea_ice)

    desert = np.zeros((H, W))
    lat = np.radians(lat_deg)
    lon_deg = (-180.0 + (np.arange(W) + 0.5) * 360.0 / W)[None, :]
    for la, lo, hy, hx, s in _rows(DESERTS, 5):
        dy = (lat_deg - la) / hy
        dlon = (lon_deg - lo + 540.0) % 360.0 - 180.0
        dx = dlon / hx
        desert = np.maximum(desert, s * np.exp(-0.5 * (dx * dx + dy * dy) ** 1.6))
    desert = np.clip(desert * 1.15, 0.0, 1.0) * land_s

    metros = _rows(METROS, 3)
    people = _gauss(W, H, [(la, lo, 0.28 + 0.06 * math.sqrt(m), m / 3.0) for la, lo, m in metros])
    people += _gauss(W, H, [(la, lo, r, w * 1.6) for la, lo, r, w in _rows(DENSE, 4)])
    people = people * land_s * (1.0 - 0.85 * desert) * (1.0 - ice_f) + 0.035 * land_s * (1.0 - desert) * (1.0 - ice_f)
    people = np.clip(people / np.percentile(people[people > 0.05], 99.5), 0.0, 1.0)
    del lat
    return {"land": land_s.astype(np.float32), "people": people.astype(np.float32),
            "desert": desert.astype(np.float32), "ice": ice_f.astype(np.float32)}


def home_vector(lat, lon):
    la, lo = math.radians(lat), math.radians(lon)
    return np.array([math.cos(la) * math.cos(lo), math.cos(la) * math.sin(lo), math.sin(la)])


def geo_frame(lat, lon):
    """Rows: the east, north and up unit vectors at (lat, lon) in Earth-fixed coordinates. World = M @ earth, so
    home maps to +Z and north to +Y."""
    la, lo = math.radians(lat), math.radians(lon)
    e = np.array([-math.sin(lo), math.cos(lo), 0.0])
    n = np.array([-math.sin(la) * math.cos(lo), -math.sin(la) * math.sin(lo), math.cos(la)])
    return np.array([e, n, home_vector(lat, lon)])


def population_within(angles, home_lat, home_lon, exclude_rad=0.0):
    """Share of the people map (by area) within each angular distance (radians) of home; people closer than
    exclude_rad are left out of both the share and the total (they are counted another way)."""
    m = maps()
    H, W = m["people"].shape
    lat = np.radians(-90.0 + (np.arange(H) + 0.5) * 180.0 / H)[:, None]
    lon = np.radians(-180.0 + (np.arange(W) + 0.5) * 360.0 / W)[None, :]
    la, lo = math.radians(home_lat), math.radians(home_lon)
    d = np.arccos(np.clip(np.sin(lat) * math.sin(la) + np.cos(lat) * math.cos(la) * np.cos(lon - lo), -1, 1))
    w = m["people"] * np.cos(lat)
    w = np.where(d >= exclude_rad, w, 0.0)
    order = np.argsort(d.ravel())
    cum = np.cumsum(w.ravel()[order])
    cum /= cum[-1]
    return np.interp(np.asarray(angles, float), d.ravel()[order], cum)


