def _image(name, W=2048, H=1024):
    if name in bpy.data.images:
        return bpy.data.images[name]
    m = maps(W, H)
    img = bpy.data.images.new(name, W, H, alpha=True, float_buffer=False)
    img.colorspace_settings.name = "Non-Color"            # before the pixels (changing it later blanks the image)
    img.alpha_mode = "CHANNEL_PACKED"
    rgba = np.stack([m["land"], np.sqrt(m["people"]), m["desert"], m["ice"]], axis=-1)
    img.pixels.foreach_set(rgba.astype(np.float32).ravel())
    img.pack()
    return img


def _vl(nt, name, sock="Fac"):
    return nt.node("ShaderNodeAttribute", attribute_type="VIEW_LAYER", attribute_name=name).outputs[sock]


def _vec(nt, op, a, b=None, scale=None):
    nd = nt.node("ShaderNodeVectorMath", operation=op)
    nt.feed(nd.inputs[0], a)
    if b is not None:
        nt.feed(nd.inputs[1], b)
    if scale is not None:
        nt.feed(nd.inputs["Scale"], scale)
    return nd.outputs["Value" if op in ("DOT_PRODUCT", "LENGTH", "DISTANCE") else "Vector"]


def _noise(nt, vec, scale, detail=4.0, rough=0.55, lac=2.0):
    n = nt.node("ShaderNodeTexNoise")
    n.inputs["Scale"].default_value = scale
    n.inputs["Detail"].default_value = detail
    n.inputs["Roughness"].default_value = rough
    if "Lacunarity" in n.inputs:
        n.inputs["Lacunarity"].default_value = lac
    nt.links.new(vec, n.inputs["Vector"])
    return n.outputs["Fac"]


def _smooth(nt, x, lo, hi):
    t = nt.math("DIVIDE", nt.math("SUBTRACT", x, lo), hi - lo, clamp=True)
    return nt.math("MULTIPLY", nt.math("MULTIPLY", t, t), nt.math("SUBTRACT", 3.0, nt.math("MULTIPLY", t, 2.0)))


def _geo(nt, M, centre):
    """(world position, unit vector from the planet's centre, earth-fixed unit vector, lon/lat UV) sockets."""
    pos = nt.node("ShaderNodeNewGeometry").outputs["Position"]
    rel = _vec(nt, "SUBTRACT", pos, tuple(centre))
    n = _vec(nt, "NORMALIZE", rel)
    comb = nt.node("ShaderNodeCombineXYZ")
    for i in range(3):
        nt.links.new(_vec(nt, "DOT_PRODUCT", n, tuple(float(M[j][i]) for j in range(3))), comb.inputs[i])
    g = comb.outputs[0]
    sep = nt.node("ShaderNodeSeparateXYZ")
    nt.links.new(g, sep.inputs[0])
    lon = nt.math("ARCTAN2", sep.outputs["Y"], sep.outputs["X"])
    lat = nt.math("ARCSINE", nt.math("MINIMUM", nt.math("MAXIMUM", sep.outputs["Z"], -1.0), 1.0))
    uv = nt.node("ShaderNodeCombineXYZ")
    nt.links.new(nt.math("ADD", nt.math("MULTIPLY", lon, 1 / (2 * math.pi)), 0.5), uv.inputs[0])
    nt.links.new(nt.math("ADD", nt.math("MULTIPLY", lat, 1 / math.pi), 0.5), uv.inputs[1])
    return pos, n, g, uv.outputs[0]


def _maps_node(nt, img, uv):
    tex = nt.node("ShaderNodeTexImage")
    tex.image = img
    tex.interpolation = "Linear"
    tex.extension = "REPEAT"
    nt.links.new(uv, tex.inputs["Vector"])
    sc = nt.node("ShaderNodeSeparateColor")
    nt.links.new(tex.outputs["Color"], sc.inputs[0])
    return sc.outputs[0], sc.outputs[1], sc.outputs[2], tex.outputs["Alpha"]


def suburb_color(nt, pos):
    """Suburbs from the air: small houses (terracotta and slate roofs) in gardens, on a 64 m grid of lanes. pos is
    the world position in metres. Used by the planet near home and by flat worlds that sit on it, so they match."""
    hv = nt.node("ShaderNodeTexVoronoi")
    hv.inputs["Scale"].default_value = 1 / 16.0
    nt.links.new(pos, hv.inputs["Vector"])
    house = nt.math("LESS_THAN", hv.outputs["Distance"], 0.30)
    roof = nt.ramp(_sep0(nt, hv.outputs["Color"]), [(0.0, (0.34, 0.16, 0.10)), (0.45, (0.42, 0.22, 0.14)),
                                                   (0.7, (0.24, 0.25, 0.27)), (1.0, (0.36, 0.35, 0.33))], constant=True)
    garden = nt.mix_color(_noise(nt, pos, 1 / 12.0, 4.0), (0.07, 0.12, 0.04, 1.0), (0.15, 0.20, 0.08, 1.0))
    col = nt.mix_color(house, garden, roof)
    sep = nt.node("ShaderNodeSeparateXYZ")
    nt.links.new(pos, sep.inputs[0])
    lx = nt.math("LESS_THAN", nt.math("FRACT", nt.math("DIVIDE", sep.outputs["X"], 64.0)), 0.09)
    ly = nt.math("LESS_THAN", nt.math("FRACT", nt.math("DIVIDE", sep.outputs["Y"], 64.0)), 0.09)
    return nt.mix_color(nt.math("MAXIMUM", lx, ly), col, (0.20, 0.20, 0.20, 1.0))


def ground_fine(nt, pos, city_r=(6500.0, 15000.0)):
    """The ground from the air in metres: fields (each its own crop) with hedges, woods, villages, and suburbs round
    home out to city_r (fading from the first radius to the second). Returns (colour, town mask)."""
    cells = nt.node("ShaderNodeTexVoronoi")
    cells.inputs["Scale"].default_value = 1 / 380.0
    nt.links.new(pos, cells.inputs["Vector"])
    crop = nt.ramp(_sep0(nt, cells.outputs["Color"]),
                   [(0.0, (0.10, 0.20, 0.04)), (0.16, (0.26, 0.21, 0.12)), (0.30, (0.15, 0.25, 0.05)),
                    (0.45, (0.33, 0.29, 0.15)), (0.58, (0.19, 0.14, 0.08)), (0.72, (0.12, 0.22, 0.05)),
                    (0.86, (0.38, 0.33, 0.12)), (1.0, (0.22, 0.27, 0.08))], constant=True)
    crop = nt.mix_color(nt.math("MULTIPLY", _noise(nt, pos, 1 / 60.0, 3.0), 0.35), crop, (0.10, 0.12, 0.05, 1.0))
    hedge = nt.math("LESS_THAN", _edge(nt, pos, 1 / 380.0), 0.022)
    crop = nt.mix_color(nt.math("MULTIPLY", hedge, 0.5), crop, (0.04, 0.07, 0.03, 1.0))
    woods = _smooth(nt, _noise(nt, pos, 1 / 2600.0, 6.0, 0.6), 0.55, 0.61)
