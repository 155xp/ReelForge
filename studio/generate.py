GENERATED_MARK = "generated by ReelForge onboarding"
BOOTSTRAP_MARK = "reelforge-bootstrap"

CADENCE = {"2/day": (2, 14, "2 videos a day"), "1/day": (1, 7, "1 video a day"),
           "3/week": (0, 3, "3 videos a week"), "1/week": (0, 1, "1 video a week")}
LENGTHS = {"61-75": (61.0, 75.0), "45-60": (45.0, 60.0), "30-45": (30.0, 45.0)}
QUALITY = {
    "max": ("Max", "the best video you are capable of, with no shortcuts, as many passes as it takes, and every "
                   "frame deliberate. Time and usage are not the constraint; quality is. If a choice is between done "
                   "and great, keep going until it's great."),
    "high": ("High", "a great video, checked carefully: fix every fault QA or your review finds, without endless "
                     "optional polish."),
    "fast": ("Fast", "quick drafts to test ideas: simpler scenes and fewer passes, but still checked by QA and your "
                     "own review before anything ships."),
}


EFFORT = {"max": "max", "high": "high", "fast": "medium"}       # Claude Code effort level per quality choice


def write_claude_settings(s: dict) -> Path | None:
    """Model and effort for Claude Code in this folder, in .claude/settings.local.json (per computer, never shared).
    Other keys already in the file (permissions and the like) are kept. Max effort needs the
    CLAUDE_CODE_EFFORT_LEVEL variable: the effortLevel key only goes up to xhigh."""
    if s["ai"]["assistant"] not in ("claude", "both"):
        return None
    path = P.ROOT / ".claude" / "settings.local.json"
    data: dict = {}
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            shutil.copy2(path, path.with_suffix(".json.bak"))
    env = data.setdefault("env", {})
    effort = EFFORT[s["ai"]["quality"]]
    data["model"] = "opus"
    if effort == "max":
        env["CLAUDE_CODE_EFFORT_LEVEL"] = "max"
        data.pop("effortLevel", None)
    else:
        env.pop("CLAUDE_CODE_EFFORT_LEVEL", None)
        data["effortLevel"] = effort
    if not env:
        data.pop("env")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
    return path


def _handle(h: str) -> str:
    h = (h or "").strip()
    if not h or h.startswith(("http://", "https://", "@")):
        return h
    return "@" + h


def _lines(text) -> list[str]:
    if isinstance(text, (list, tuple)):
        return [str(t).strip() for t in text if str(t).strip()]
    return [ln.strip(" -*\t") for ln in str(text or "").splitlines() if ln.strip(" -*\t")]


def settings_from(a: dict) -> dict:
    """Validated answers -> the studio.toml settings."""
    fmt_key = a.get("format", "doubling")
    fmt = FORMATS[fmt_key]
    lo, hi = LENGTHS.get(a.get("length", "61-75")) or parse_length(a.get("length_custom", "61-75"))
    lufs = S.LOUDNESS.get(a.get("loudness", "quiet"), S.LOUDNESS["quiet"])[0]
    per_day, per_week, _ = CADENCE.get(a.get("cadence", "2/day"), CADENCE["2/day"])
    platforms = list(a.get("platforms") or S.PLATFORMS)
    today = dt.date.today().isoformat()
    return {
        "studio": {"kit_version": KIT_VERSION, "created": a.get("_created") or today, "updated": today},
        "channel": {
            "name": a["channel_name"].strip(),
            "creator": a.get("creator", "").strip(),
            "about": a.get("about", "").strip(),
            "audience": a.get("audience", "").strip(),
            "tone": list(a.get("tone") or []),
            "language": "English",
        },
        "format": {
            "template": fmt_key,
            "series": a.get("series", fmt["series"]).strip() or fmt["short"],
            "premise": fmt["premise"],
            "twist": a.get("twist", "").strip(),
            "custom": a.get("custom_format", "").strip(),
            "references": _lines(a.get("references", "")),
            "subjects": _lines(a.get("subjects", "")),
            "avoid": a.get("avoid", "").strip(),
            "episode_label": "Ep. {n}",
        },
        "video": {
            "fps": 30,
            "min_seconds": lo,
            "max_seconds": hi,
            "hud": bool(a.get("hud", fmt["hud"])),
            "loop": bool(fmt["loop"]),
            "cta": (a.get("cta") or "FOLLOW FOR MORE").strip(),
            "style": a.get("style", "cinematic"),
            "style_notes": a.get("style_notes", "").strip(),
            "voiceover": False,
        },
        "sound": {"loudness": a.get("loudness", "quiet"), "target_lufs": lufs},
        "captions": {
            "max_hashtags": int(a.get("max_hashtags", 5)),
            "tiktok_first_tag": str(a.get("tiktok_first_tag", "fyp") or "").lstrip("#").strip(),
            "hashtags_on_x": bool(a.get("hashtags_on_x", False)),
            "title_max_chars": 80,
            "default_tags": S.tag_list(a.get("default_tags", "")),
        },
        "platforms": {
            "enabled": platforms,
            "handles": {p: _handle(a.get(f"handle_{p}", "")) for p in S.PLATFORMS if p in platforms},
            "background_stats": bool(a.get("background_stats", True)),
        },
        "schedule": {"per_day": per_day, "per_week": per_week, "post_times": a.get("post_times", "").strip(),
                     "timezone": a.get("timezone", "").strip()},
        "ai": {"assistant": a.get("assistant", "claude"), "quality": a.get("quality", "max"),
               "ultracode": bool(a.get("ultracode", True)) and a.get("assistant", "claude") in ("claude", "both")},
    }


