def _put(width: int, height: int, parts: list) -> list[str]:
    """A grid with each (glyph, colour, column, row) drawn in."""
    grid = [["."] * width for _ in range(height)]
    for glyph, colour, x, y in parts:
        for dy, line in enumerate(glyph):
            for dx, ch in enumerate(line):
                if ch == "#":
                    grid[y + dy][x + dx] = colour
    return ["".join(line) for line in grid]


